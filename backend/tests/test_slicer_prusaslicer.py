def test_slice_parses_real_looking_gcode_end_to_end(tmp_path: Path) -> None:
    """Exercises the full slice() path against a mocked subprocess that
    writes a gcode file with representative header comments, proving the
    glob + read + parse plumbing works end to end without a real binary."""
    service = PrusaSlicerService(binary_path="prusa-slicer")
    stl_path = tmp_path / "part.stl"
    stl_path.write_text("solid part\nendsolid part\n")

    def fake_run(argv, cwd, **kwargs):
        output_index = argv.index("--output")
        gcode_path = Path(argv[output_index + 1])
        gcode_path.write_text(
            "; estimated printing time (normal mode) = 1h 2m 3s\n; filament used [g] = 15.5\n"
        )
        return subprocess.CompletedProcess(args=argv, returncode=0, stdout="Slicing result exported", stderr="")

    with (
        patch.object(PrusaSlicerService, "_resolve_binary", return_value="/fake/prusa-slicer"),
        patch("subprocess.run", side_effect=fake_run),
    ):
        result = service.slice(stl_path, "generic_pla", _candidate())

    assert result.success is True
    assert result.print_time_seconds == 3723
    assert result.filament_grams == pytest.approx(15.5)
    assert result.warnings == []
