import pytest

from app.models.candidate import CandidateConfiguration
from app.slicer.base import SlicerUnavailableError
from app.slicer.prusaslicer import PrusaSlicerService


def _candidate(**overrides) -> CandidateConfiguration:
    defaults = dict(run_id="run-1", layer_height=0.2, infill_percent=20, perimeter_count=3)
    defaults.update(overrides)
    return CandidateConfiguration(**defaults)


def test_slice_raises_when_binary_missing(tmp_path: Path) -> None:
    service = PrusaSlicerService(binary_path="definitely-not-a-real-binary-xyz")
    stl_path = tmp_path / "part.stl"
    stl_path.write_text("solid part\nendsolid part\n")

    with pytest.raises(SlicerUnavailableError):
        service.slice(stl_path, "generic_pla", _candidate())


def test_slice_reports_missing_stl_without_raising(tmp_path: Path) -> None:
    service = PrusaSlicerService(binary_path="definitely-not-a-real-binary-xyz")
    result = service.slice(tmp_path / "does-not-exist.stl", "generic_pla", _candidate())
    assert result.success is False
    assert "not found" in result.error


def test_build_command_includes_mvp_variables(tmp_path: Path) -> None:
    service = PrusaSlicerService()
    candidate = _candidate(
        layer_height=0.28,
        infill_percent=15,
        perimeter_count=4,
        supports_enabled=True,
        orientation_x=5,
        orientation_y=7,
        orientation_z=90,
    )

    command = service.build_command(
        stl_path=tmp_path / "part.stl",
        printer_profile="generic_pla",
        candidate_configuration=candidate,
        output_dir=tmp_path,
        binary_path="prusa-slicer",
    )

    assert "--layer-height" in command.argv
    assert "0.28" in command.argv
    assert "--perimeters" in command.argv
    assert "4" in command.argv
    assert "--support-material" in command.argv
    assert "--rotate-x" in command.argv
    assert "5.0" in command.argv
    assert "--rotate-y" in command.argv
    assert "7.0" in command.argv
    assert "--rotate" in command.argv
    assert "90.0" in command.argv
    assert "--export-gcode" in command.argv
    assert "--output" in command.argv


def test_build_command_fill_density_includes_percent_sign(tmp_path: Path) -> None:
    """Regression test: a bare number (no `%`) is silently reinterpreted by
    PrusaSlicer's legacy-config compatibility layer as an old-style 0..1
    fraction and multiplied by 100 (20 -> 2000%). Confirmed against
    PrintConfigDef::handle_legacy in PrintConfig.cpp — see module docstring
    in app/slicer/prusaslicer.py.
    """
    service = PrusaSlicerService()
    candidate = _candidate(infill_percent=20)

    command = service.build_command(
        stl_path=tmp_path / "part.stl",
        printer_profile="generic_pla",
        candidate_configuration=candidate,
        output_dir=tmp_path,
        binary_path="prusa-slicer",
    )

    fill_density_index = command.argv.index("--fill-density")
    assert command.argv[fill_density_index + 1] == "20%"


